// Turns data/cin_reference_codes_v2.csv into src/reference-data.js.
// Run: node scripts/build-reference-data.mjs
// The page loads the generated JS file, so it needs no database and no network call.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const csvPath = join(root, 'data', 'cin_reference_codes_v2.csv');
const outPath = join(root, 'src', 'reference-data.js');

// Small CSV reader that understands "quoted, fields" and "" escapes.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (inQuotes) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') inQuotes = false;
      else field += ch;
    } else if (ch === '"') inQuotes = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.some((c) => c !== '')) rows.push(row);
      row = [];
    } else field += ch;
  }
  if (field !== '' || row.length) { row.push(field); if (row.some((c) => c !== '')) rows.push(row); }
  return rows;
}

// Files saved from Excel often start with an invisible byte-order mark; drop it.
const csvText = readFileSync(csvPath, 'utf8').replace(/^﻿/, '');
const [header, ...body] = parseCsv(csvText);
const expected = ['code', 'meaning', 'type', 'status', 'notes'];
if (JSON.stringify(header) !== JSON.stringify(expected)) {
  throw new Error('Unexpected CSV header: ' + header.join(','));
}

const TYPE_TO_KEY = { listing: 'listing', state: 'state', company_type: 'companyType' };
const STATUSES = new Set(['current', 'legacy', 'alias', 'observed']);
const data = { listing: {}, state: {}, companyType: {} };

for (const [code, meaning, type, status, notes] of body) {
  const key = TYPE_TO_KEY[type];
  if (!key) throw new Error(`Row ${code}: unknown type "${type}"`);
  if (!STATUSES.has(status)) throw new Error(`Row ${code}: unknown status "${status}"`);
  if (data[key][code]) throw new Error(`Duplicate ${type} code ${code}`);
  data[key][code] = { meaning, status, notes };
}

const out = `// GENERATED by scripts/build-reference-data.mjs from data/cin_reference_codes_v2.csv.
// Do not edit by hand: change the CSV and run the script again.
(function (root) {
  const data = ${JSON.stringify(data, null, 2)};
  if (typeof module !== 'undefined' && module.exports) module.exports = data;
  else root.CIN_REFERENCE = data;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;

writeFileSync(outPath, out);
const counts = Object.entries(data).map(([k, v]) => `${k}: ${Object.keys(v).length}`).join(', ');
console.log(`Wrote ${outPath} (${counts})`);
